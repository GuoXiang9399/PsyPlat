export function getLang(): Lang {
  return currentLang
}

const listeners = new Set<() => void>()

function applyLangMeta(): void {
  if (typeof document === 'undefined') return
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en'
  document.title = t('meta_title')
  try {
    const m = document.querySelector('meta[name="description"]')
    if (m) m.setAttribute('content', t('meta_desc'))
  } catch {}
}

export function initLang(): void {
  try {
    const saved = localStorage.getItem(LANG_KEY)
    if (saved === 'zh' || saved === 'en') currentLang = saved
  } catch {}
  applyLangMeta()
}

export function setLang(lang: Lang): void {
  currentLang = lang
  try { localStorage.setItem(LANG_KEY, lang) } catch {}
  applyLangMeta()
  listeners.forEach((fn) => fn())
}

function subscribe(fn: () => void): () => void {
  listeners.add(fn)
  return () => { listeners.delete(fn) }
}

export function useLang(): Lang {
  return useSyncExternalStore(subscribe, getLang, () => 'zh' as Lang)
}

/** 取当前语言文案；英文缺失时回退中文，再回退 key 本身 */
export function t(key: string): string {
  return DICT[currentLang][key] ?? DICT.zh[key] ?? key
}

/** 带参格式化：q_progress 等 */
export function tFmt(key: string, vars: Record<string, string | number>): string {
  let s = t(key)
  for (const [k, v] of Object.entries(vars)) {
    s = s.split('{' + k + '}').join(String(v))
  }
  return s
}

